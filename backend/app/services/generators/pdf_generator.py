"""AI PDF Maker / Document Generator for Cognexa AI.

Creates professional multi-page PDF documents with styled headers, executive summaries,
structured sections, tables, code snippets, and automated page numbering using ReportLab.
"""

from __future__ import annotations

import logging
import os
import re
from pathlib import Path
from typing import Any, Dict, List, Optional
import uuid

logger = logging.getLogger(__name__)

EXPORTS_DIR = Path("exports").resolve()
EXPORTS_DIR.mkdir(parents=True, exist_ok=True)


class NumberedCanvas:
    """Canvas wrapper that dynamically adds 'Page X of Y' and header to all pages."""

    def __init__(self, *args, **kwargs):
        self.canvas_maker = args
        self.canvas_kwargs = kwargs

    def __call__(self, *args, **kwargs):
        from reportlab.pdfgen import canvas

        class _NumberedCanvas(canvas.Canvas):
            def __init__(self, *c_args, **c_kwargs):
                super().__init__(*c_args, **c_kwargs)
                self._saved_page_states = []

            def showPage(self):
                self._saved_page_states.append(dict(self.__dict__))
                self._startPage()

            def save(self):
                num_pages = len(self._saved_page_states)
                for state in self._saved_page_states:
                    self.__dict__.update(state)
                    self.draw_header_footer(num_pages)
                    super().showPage()
                super().save()

            def draw_header_footer(self, page_count: int):
                from reportlab.lib.colors import HexColor

                self.saveState()
                self.setFont("Helvetica", 8)
                self.setFillColor(HexColor("#64748b"))

                # Header (on pages > 1)
                if self._pageNumber > 1:
                    self.drawString(54, 755, "Cognexa Autonomous Engineering Suite • Technical Document")
                    self.setStrokeColor(HexColor("#cbd5e1"))
                    self.setLineWidth(0.5)
                    self.line(54, 747, 558, 747)

                # Footer
                self.setStrokeColor(HexColor("#cbd5e1"))
                self.setLineWidth(0.5)
                self.line(54, 45, 558, 45)
                self.drawString(54, 32, "Generated by Cognexa AI  |  Confidential & Proprietary")
                page_text = f"Page {self._pageNumber} of {page_count}"
                self.drawRightString(558, 32, page_text)
                self.restoreState()

        return _NumberedCanvas(*args, **kwargs)


def generate_pdf_report(
    title: str,
    sections: Optional[List[Dict[str, Any]]] = None,
    summary: Optional[str] = None,
    author: str = "Cognexa Autonomous AI",
) -> Dict[str, Any]:
    """Generate a publication-grade PDF report.

    Args:
        title: Document title.
        sections: List of section dicts with 'heading' and 'content' (paragraphs or list of points).
        summary: Executive summary paragraph.
        author: Document creator attribution.

    Returns:
        Dict with status, filename, page_count, download_url.
    """
    try:
        from reportlab.lib import colors
        from reportlab.lib.pagesizes import letter
        from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
        from reportlab.platypus import (
            HRFlowable,
            KeepTogether,
            Paragraph,
            SimpleDocTemplate,
            Spacer,
            Table,
            TableStyle,
        )
    except ImportError:
        logger.error("reportlab is not installed.")
        raise RuntimeError("reportlab library is required for PDF document generation.")

    clean_title = re.sub(r"[^a-zA-Z0-9_\-\s]", "", title).strip()
    clean_filename = re.sub(r"\s+", "_", clean_title)[:40] or "Document"
    unique_suffix = uuid.uuid4().hex[:6]
    filename = f"{clean_filename}_{unique_suffix}.pdf"
    out_path = EXPORTS_DIR / filename

    doc = SimpleDocTemplate(
        str(out_path),
        pagesize=letter,
        leftMargin=54,
        rightMargin=54,
        topMargin=54,
        bottomMargin=54,
    )

    styles = getSampleStyleSheet()

    # Custom typography styles
    title_style = ParagraphStyle(
        "DocTitle",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=24,
        leading=28,
        textColor=colors.HexColor("#0f172a"),
        spaceAfter=6,
    )

    subtitle_style = ParagraphStyle(
        "DocSubtitle",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=12,
        leading=16,
        textColor=colors.HexColor("#0284c7"),
        spaceAfter=14,
    )

    h1_style = ParagraphStyle(
        "DocHeading1",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=14,
        leading=18,
        textColor=colors.HexColor("#1e293b"),
        spaceBefore=14,
        spaceAfter=6,
    )

    h2_style = ParagraphStyle(
        "DocHeading2",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=11,
        leading=15,
        textColor=colors.HexColor("#334155"),
        spaceBefore=10,
        spaceAfter=4,
    )

    body_style = ParagraphStyle(
        "DocBody",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=9.5,
        leading=14,
        textColor=colors.HexColor("#334155"),
        spaceAfter=8,
    )

    bullet_style = ParagraphStyle(
        "DocBullet",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=9,
        leading=13.5,
        textColor=colors.HexColor("#1e293b"),
        leftIndent=15,
        spaceAfter=4,
    )

    meta_style = ParagraphStyle(
        "DocMeta",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=8.5,
        leading=11,
        textColor=colors.HexColor("#475569"),
    )

    story = []

    # 1. Header Banner / Badge
    banner_data = [
        [
            Paragraph("<b>COGNEXA AI</b> • KNOWLEDGE & ENGINEERING SYSTEMS", meta_style),
            Paragraph("OFFICIAL REPORT", meta_style),
        ]
    ]
    banner_table = Table(banner_data, colWidths=[350, 154])
    banner_table.setStyle(
        TableStyle([
            ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
            ("TEXTCOLOR", (1, 0), (1, 0), colors.HexColor("#0284c7")),
            ("ALIGN", (1, 0), (1, 0), "RIGHT"),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
        ])
    )
    story.append(banner_table)
    story.append(HRFlowable(width="100%", thickness=2, color=colors.HexColor("#0284c7"), spaceAfter=14))

    # 2. Main Title & Subtitle
    story.append(Paragraph(title, title_style))
    story.append(Paragraph(f"Autonomous Comprehensive Synthesis • Authored by {author}", subtitle_style))

    # 3. Metadata Table
    meta_rows = [
        [
            Paragraph("<b>Subject:</b>", meta_style),
            Paragraph(title, body_style),
            Paragraph("<b>Date:</b>", meta_style),
            Paragraph("Current Operational Cycle", body_style),
        ],
        [
            Paragraph("<b>Engine:</b>", meta_style),
            Paragraph("Cognexa Core 2.0 (LangGraph + Vector Memory)", body_style),
            Paragraph("<b>Security:</b>", meta_style),
            Paragraph("Verified & Sandboxed", body_style),
        ],
    ]
    meta_table = Table(meta_rows, colWidths=[60, 220, 60, 164])
    meta_table.setStyle(
        TableStyle([
            ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#f8fafc")),
            ("BOX", (0, 0), (-1, -1), 1, colors.HexColor("#e2e8f0")),
            ("INNERGRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#f1f5f9")),
            ("TOPPADDING", (0, 0), (-1, -1), 6),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
            ("LEFTPADDING", (0, 0), (-1, -1), 8),
            ("RIGHTPADDING", (0, 0), (-1, -1), 8),
        ])
    )
    story.append(meta_table)
    story.append(Spacer(1, 14))

    # 4. Executive Summary
    if not summary:
        from app.services.content_synthesizer import _match_curated_knowledge
        curated = _match_curated_knowledge(title)
        if curated and curated.get("summary"):
            summary = curated["summary"]
        else:
            summary = (
                f"This technical document outlines the systematic engineering principles, architectural patterns, "
                f"and operational methodologies concerning {title}. The analysis synthesizes key theoretical benchmarks, "
                f"trade-offs, and implementation considerations compiled by the Cognexa AI reasoning pipeline."
            )

    story.append(Paragraph("1. Executive Summary", h1_style))
    story.append(Paragraph(summary, body_style))
    story.append(Spacer(1, 8))

    # 5. Core Sections
    if not sections:
        sections = _generate_default_sections(title)

    from reportlab.platypus import PageBreak

    for idx, sec in enumerate(sections, start=2):
        raw_h = sec.get('heading', 'Analysis').strip()
        if re.match(r'^(question|\d+\.|\bsection\b|\bmodule\b|\bunit\b)', raw_h, re.IGNORECASE):
            sec_heading = raw_h
        else:
            sec_heading = f"{idx}. {raw_h}"

        if sec.get("page_break"):
            story.append(PageBreak())

        story.append(Paragraph(sec_heading, h1_style))

        content = sec.get("content")
        if isinstance(content, str):
            for para in content.split("\n\n"):
                if para.strip():
                    story.append(Paragraph(para.strip(), body_style))
        elif isinstance(content, list):
            for item in content:
                story.append(Paragraph(f"• &nbsp; {str(item)}", bullet_style))

        # Check for sub-points
        subpoints = sec.get("points")
        if subpoints and isinstance(subpoints, list):
            for pt in subpoints:
                story.append(Paragraph(f"• &nbsp; {str(pt)}", bullet_style))

        story.append(Spacer(1, 6))

    # Build document with custom numbered canvas
    canvas_factory = NumberedCanvas()
    doc.build(story, canvasmaker=canvas_factory)

    size_kb = round(out_path.stat().st_size / 1024, 1)
    download_url = f"http://localhost:8001/downloads/{filename}"

    logger.info("Generated PDF report: %s (%s KB)", filename, size_kb)

    return {
        "status": "success",
        "filename": filename,
        "title": title,
        "size_kb": size_kb,
        "download_url": download_url,
    }


def _generate_default_sections(topic: str) -> List[Dict[str, Any]]:
    """Generate comprehensive report sections for any engineering topic."""
    from app.services.content_synthesizer import _match_curated_knowledge, _build_dynamic_engineering_notes
    curated = _match_curated_knowledge(topic)
    if curated and curated.get("sections"):
        return curated["sections"]
    return _build_dynamic_engineering_notes(topic)["sections"]

